#!/usr/bin/env bash
# Write terraform/terraform.tfvars
#   ./scripts/configure.sh              # interactive (CF prefills + prompts)
#   ./scripts/configure.sh --from-env   # non-interactive from repo .env
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TF_DIR="$ROOT/terraform"
OUT="$TF_DIR/terraform.tfvars"

write_tfvars() {
  local ga="$1" region="$2" source_id="$3" new_name="$4" new_sub="$5"
  local cf_org_name="$6" space="$7" admin_email="$8" create_sub="$9"
  local ent_svc="${10}" sub_app="${11}" plan="${12}" mem="${13}"
  local cf_plan="${14:-trial}"

  cat > "$OUT" <<EOF
# Generated by scripts/configure.sh — do not commit
globalaccount_subdomain = "${ga}"
region                  = "${region}"

source_subaccount_id = "${source_id}"

recovery_subaccount_name      = "${new_name}"
recovery_subaccount_subdomain = "${new_sub}"

cf_org_name      = "${cf_org_name}"
cf_space_name    = "${space}"
admin_user_email = "${admin_email}"

free_source_entitlements                      = true
delete_source_integration_suite_subscription  = true
create_integration_suite_subscription         = ${create_sub}

# Entitlement service_name ≠ subscription app_name on many trials
integration_suite_entitlement_service_name = "${ent_svc}"
integration_suite_subscription_app_name    = "${sub_app}"
integration_suite_plan_name                = "${plan}"
cf_runtime_amount                          = ${mem}
cf_environment_plan_name                   = "${cf_plan}"
EOF
}

print_next() {
  local ga="$1"
  echo
  echo "Wrote $OUT"
  echo
  echo "Next — separate shell commands (not prompt answers):"
  echo "  1) ./scripts/btp_login.sh"
  echo "     (or: btp login --url https://cli.btp.cloud.sap --sso --subdomain \"${ga}\")"
  echo "  2) source ./scripts/load_env.sh    # exports USE_BTPCLI_SESSION / optional password"
  echo "  3) ./scripts/delete_source_integration_suite.sh"
  echo "  4) ./scripts/free_source_entitlements.sh   # amount 0 via btp CLI (Terraform cannot)"
  echo "  5) cd terraform && terraform plan && terraform apply"
  echo "  6) ../scripts/create_cf_space.sh"
}

# ---------- --from-env ----------
if [[ "${1:-}" == "--from-env" ]]; then
  echo "=== configure from .env ==="
  # shellcheck disable=SC1091
  source "$ROOT/scripts/load_env.sh"

  GA="${GLOBALACCOUNT_SUBDOMAIN:-}"
  REGION="${REGION:-us10}"
  SOURCE_ID="${SOURCE_SUBACCOUNT_ID:-}"
  NEW_NAME="${RECOVERY_SUBACCOUNT_NAME:-is-recovery}"
  NEW_SUB="${RECOVERY_SUBACCOUNT_SUBDOMAIN:-}"
  CF_ORG_NAME="${CF_ORG_NAME:-is-recovery-org}"
  SPACE="${CF_SPACE_NAME:-DEV}"
  ADMIN_EMAIL="${ADMIN_USER_EMAIL:-}"
  ENT_SVC="${INTEGRATION_SUITE_ENTITLEMENT_SERVICE_NAME:-integrationsuite-trial}"
  SUB_APP="${INTEGRATION_SUITE_SUBSCRIPTION_APP_NAME:-it-cpitrial06-prov}"
  # Back-compat: old single name was often wrong for subscriptions
  if [[ -n "${INTEGRATION_SUITE_APP_NAME:-}" && -z "${INTEGRATION_SUITE_SUBSCRIPTION_APP_NAME:-}" ]]; then
    SUB_APP="$INTEGRATION_SUITE_APP_NAME"
  fi
  PLAN="${INTEGRATION_SUITE_PLAN_NAME:-trial}"
  MEM="${CF_RUNTIME_AMOUNT:-4}"
  CF_PLAN="${CF_ENVIRONMENT_PLAN_NAME:-trial}"
  CREATE_SUB="${CREATE_INTEGRATION_SUITE_SUBSCRIPTION:-true}"

  missing=()
  [[ -z "$GA" ]] && missing+=("GLOBALACCOUNT_SUBDOMAIN")
  [[ -z "$SOURCE_ID" || "$SOURCE_ID" == "00000000-0000-0000-0000-000000000000" ]] && missing+=("SOURCE_SUBACCOUNT_ID")
  [[ -z "$NEW_SUB" ]] && missing+=("RECOVERY_SUBACCOUNT_SUBDOMAIN")
  [[ -z "$ADMIN_EMAIL" ]] && missing+=("ADMIN_USER_EMAIL")
  if ((${#missing[@]})); then
    echo "Fill these in .env first: ${missing[*]}"
    exit 1
  fi

  write_tfvars "$GA" "$REGION" "$SOURCE_ID" "$NEW_NAME" "$NEW_SUB" \
    "$CF_ORG_NAME" "$SPACE" "$ADMIN_EMAIL" "$CREATE_SUB" "$ENT_SVC" "$SUB_APP" "$PLAN" "$MEM" "$CF_PLAN"
  print_next "$GA"
  exit 0
fi

# ---------- interactive ----------
echo "=== BTP Integration Suite recovery — configure ==="
echo
echo "Tip: put values in .env and run: ./scripts/configure.sh --from-env"
echo

CF_USER=""
CF_ORG=""
CF_SPACE=""
CF_API=""
CF_REGION=""

cf_field() {
  local label="$1"
  echo "$TARGET" | sed -n "s/^${label}:[[:space:]]*//p" | head -1 | tr -d '\r'
}

if command -v cf >/dev/null 2>&1 && cf target >/dev/null 2>&1; then
  TARGET="$(cf target 2>/dev/null || true)"
  CF_USER="$(cf_field user)"
  CF_ORG="$(cf_field org)"
  CF_SPACE="$(cf_field space)"
  CF_API="$(cf_field 'API endpoint')"
  if [[ "$CF_API" =~ api\.cf\.([a-z0-9]+)- ]]; then
    CF_REGION="${BASH_REMATCH[1]}"
  elif [[ "$CF_API" =~ api\.cf\.([a-z0-9]+)\. ]]; then
    CF_REGION="${BASH_REMATCH[1]}"
  fi
  echo "Detected from cf target:"
  echo "  user:   ${CF_USER:-?}"
  echo "  org:    ${CF_ORG:-?}"
  echo "  space:  ${CF_SPACE:-?}"
  echo "  api:    ${CF_API:-?}"
  echo "  region: ${CF_REGION:-?} (guessed from API host)"
  echo
  echo "CF does NOT expose Global Account subdomain (-ga) or Subaccount GUID — still asked below."
  echo
else
  echo "No active cf target found. Run: cf login -a <API from Cockpit> --sso"
  echo "Continuing with manual prompts only."
  echo
fi

# Prefill from .env if present (optional)
if [[ -f "$ROOT/.env" ]]; then
  # shellcheck disable=SC1091
  set -a
  source "$ROOT/.env"
  set +a
  echo "Also loaded defaults from .env (press Enter to keep)."
  echo
fi

DEFAULT_GA="${GLOBALACCOUNT_SUBDOMAIN:-}"
if [[ -z "$DEFAULT_GA" && -n "${CF_ORG}" ]]; then
  DEFAULT_GA="${CF_ORG}-ga"
fi
echo "Press Enter to accept defaults in [brackets]. Do NOT paste shell commands here."
echo "Global Account subdomain: Cockpit → CLI Setup / Terraform Setup (often …trial-ga)."
read -r -p "Global Account subdomain${DEFAULT_GA:+ [$DEFAULT_GA]}: " GA
GA="${GA:-$DEFAULT_GA}"
if [[ -z "$GA" ]]; then
  echo "Global Account subdomain is required."
  exit 1
fi
if [[ "$GA" == *" "* || "$GA" == *"login"* || "$GA" == *"export "* ]]; then
  echo "That does not look like a Global Account subdomain (got: $GA)."
  echo "Copy YOUR value from Cockpit → CLI Setup (often ends with -ga)."
  exit 1
fi

DEFAULT_REGION="${REGION:-${CF_REGION:-us10}}"
read -r -p "Region for the NEW subaccount [$DEFAULT_REGION]: " REGION_IN
REGION="${REGION_IN:-$DEFAULT_REGION}"
if [[ "$REGION" == *" "* || "$REGION" == *"export"* || "$REGION" == *"USE_BTP"* ]]; then
  echo "That does not look like a region code (got: $REGION). Example: us10"
  exit 1
fi

echo
echo "Stuck / source subaccount (BTP Subaccount ID — not the CF org GUID)"
echo "  Cockpit → Account Explorer → failing subaccount → Overview → Subaccount ID"
DEFAULT_SOURCE="${SOURCE_SUBACCOUNT_ID:-}"
read -r -p "Source (stuck) subaccount GUID${DEFAULT_SOURCE:+ [$DEFAULT_SOURCE]}: " SOURCE_ID
SOURCE_ID="${SOURCE_ID:-$DEFAULT_SOURCE}"
if [[ -z "$SOURCE_ID" ]]; then
  echo "Source subaccount GUID is required."
  exit 1
fi

echo
echo "New recovery subaccount"
DEFAULT_NAME="${RECOVERY_SUBACCOUNT_NAME:-is-recovery}"
read -r -p "NEW subaccount display name [$DEFAULT_NAME]: " NEW_NAME
NEW_NAME="${NEW_NAME:-$DEFAULT_NAME}"
DEFAULT_SUB="${RECOVERY_SUBACCOUNT_SUBDOMAIN:-}"
read -r -p "NEW subaccount subdomain (globally unique, lowercase)${DEFAULT_SUB:+ [$DEFAULT_SUB]}: " NEW_SUB
NEW_SUB="${NEW_SUB:-$DEFAULT_SUB}"
if [[ -z "$NEW_SUB" ]]; then
  echo "Subdomain is required."
  exit 1
fi

DEFAULT_CF_ORG="${CF_ORG_NAME:-is-recovery-org}"
read -r -p "CF environment / org instance name on the NEW subaccount [$DEFAULT_CF_ORG]: " CF_ORG_NAME_IN
CF_ORG_NAME="${CF_ORG_NAME_IN:-$DEFAULT_CF_ORG}"

DEFAULT_SPACE="${CF_SPACE_NAME:-${CF_SPACE:-DEV}}"
DEFAULT_SPACE_UP="$(echo "$DEFAULT_SPACE" | tr '[:lower:]' '[:upper:]')"
[[ "$DEFAULT_SPACE_UP" == "DEV" ]] && DEFAULT_SPACE="DEV" || DEFAULT_SPACE="$DEFAULT_SPACE"
read -r -p "CF space name to create AFTER apply [$DEFAULT_SPACE]: " SPACE
SPACE="${SPACE:-$DEFAULT_SPACE}"

DEFAULT_EMAIL="${ADMIN_USER_EMAIL:-$CF_USER}"
read -r -p "Admin user email${DEFAULT_EMAIL:+ [$DEFAULT_EMAIL]}: " ADMIN_EMAIL
ADMIN_EMAIL="${ADMIN_EMAIL:-$DEFAULT_EMAIL}"
if [[ -z "$ADMIN_EMAIL" ]]; then
  echo "Admin email is required."
  exit 1
fi

DEFAULT_SUB_FLAG="${CREATE_INTEGRATION_SUITE_SUBSCRIPTION:-Y}"
[[ "$DEFAULT_SUB_FLAG" == "true" ]] && DEFAULT_SUB_FLAG="Y"
[[ "$DEFAULT_SUB_FLAG" == "false" ]] && DEFAULT_SUB_FLAG="n"
read -r -p "Subscribe Integration Suite on the NEW subaccount? [${DEFAULT_SUB_FLAG}/n]: " DO_SUB
DO_SUB="${DO_SUB:-$DEFAULT_SUB_FLAG}"
if [[ "$DO_SUB" =~ ^[Nn]$ ]]; then
  CREATE_SUB="false"
else
  CREATE_SUB="true"
fi

ENT_SVC="${INTEGRATION_SUITE_ENTITLEMENT_SERVICE_NAME:-integrationsuite-trial}"
SUB_APP="${INTEGRATION_SUITE_SUBSCRIPTION_APP_NAME:-it-cpitrial06-prov}"
PLAN="${INTEGRATION_SUITE_PLAN_NAME:-trial}"
MEM="${CF_RUNTIME_AMOUNT:-4}"
CF_PLAN="${CF_ENVIRONMENT_PLAN_NAME:-trial}"

write_tfvars "$GA" "$REGION" "$SOURCE_ID" "$NEW_NAME" "$NEW_SUB" \
  "$CF_ORG_NAME" "$SPACE" "$ADMIN_EMAIL" "$CREATE_SUB" "$ENT_SVC" "$SUB_APP" "$PLAN" "$MEM" "$CF_PLAN"
print_next "$GA"
